class Student {
  final String studentId;
  final String name;
  final String email;
  final int yearLevel;
  final String course;
  final String hobby;
  final String favoriteSubject;
  final String status;

  Student({
    required this.studentId,
    required this.name,
    required this.email,
    required this.yearLevel,
    required this.course,
    required this.hobby,
    required this.favoriteSubject,
    required this.status,
  });
}
